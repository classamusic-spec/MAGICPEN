/** Every doodle this module can draw. */
export const DOODLE_NAMES: string[] = Object.keys(DOODLES);

/** True when `name` is a doodle we can actually draw. */
export function hasDoodle(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(DOODLES, name);
}

/** The parts of a doodle, falling back to the mystery blob rather than nothing. */
export function doodleParts(name: string): Part[] {
  return DOODLES[name] ?? DOODLES.mystery;
}

